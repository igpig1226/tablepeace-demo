function translateText(text) {
  const trimmed = text.trim();
  if (!trimmed) return text;
  let translated = phrases.get(trimmed);
  if (!translated) for (const [pattern,fn] of patterns) {const match=trimmed.match(pattern);if(match){translated=fn(...match);break;}}
  if (!translated || translated===trimmed) return text;
  return text.replace(trimmed,translated);
}
function translateTree(root) {
  if (root.nodeType===Node.TEXT_NODE) {const next=translateText(root.nodeValue);if(next!==root.nodeValue)root.nodeValue=next;return;}
  if (root.nodeType!==Node.ELEMENT_NODE) return;
  const elements=[root,...root.querySelectorAll('*')];
  for (const el of elements) {
    if (el.tagName==='SCRIPT'||el.tagName==='STYLE') continue;
    for (const attr of ['placeholder','aria-label','title']) {const value=el.getAttribute(attr);if(value){const next=translateText(value);if(next!==value)el.setAttribute(attr,next);}}
    for (const child of [...el.childNodes]) if (child.nodeType===Node.TEXT_NODE) translateTree(child);
  }
}
